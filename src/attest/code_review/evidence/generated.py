"""Spot lockfiles, minified bundles, build or vendor output, and files marked as generated."""

from __future__ import annotations

import re
from pathlib import PurePosixPath

from ...utils.diff import DiffLine, FileDiff, parse_unified_diff
from .lockfiles import parser_for

GENERATED_FILENAMES = frozenset(
    {
        "Gemfile.lock",
        "composer.lock",
        "Pipfile.lock",
        "bun.lockb",
        "bun.lock",
        "flake.lock",
        "Podfile.lock",
        "mix.lock",
        "pubspec.lock",
        "packages.lock.json",
        "gradle.lockfile",
        "Package.resolved",
        "deno.lock",
        "Manifest.toml",
    }
)
GENERATED_SUFFIXES = (
    ".min.js",
    ".min.mjs",
    ".min.css",
    "-min.js",
    ".bundle.js",
    ".chunk.js",
    ".js.map",
    ".css.map",
    ".pb.go",
    "_pb2.py",
    "_pb2_grpc.py",
    ".pb.cc",
    ".pb.h",
    ".g.dart",
    ".freezed.dart",
    ".designer.cs",
)
GENERATED_DIRS = frozenset(
    {
        "node_modules",
        "vendor",
        "third_party",
        "dist",
        "build",
        ".next",
        ".nuxt",
        "__generated__",
        "generated",
        "bower_components",
    }
)
_MARKERS = re.compile(
    r"@generated|DO NOT EDIT|Code generated by|auto-?generated|automatically generated",
    re.IGNORECASE,
)
_MARKER_LINE_LIMIT = 10
_MINIFIED_SUFFIXES = (".js", ".mjs", ".cjs", ".css")
_MINIFIED_LINE_CHARS = 1000


def is_generated(path: str, diff_text: str = "") -> bool:
    """Return True for lockfiles, minified bundles, build or vendor output, and marked files.

    A marker or minified line counts only when the file already had it before the pull request:
    lines the pull request adds are the author's to write, so they cannot hide a file's diff.
    """
    pure = PurePosixPath(path)
    if parser_for(path) is not None or pure.name in GENERATED_FILENAMES:
        return True
    if pure.name.endswith(GENERATED_SUFFIXES):
        return True
    if any(part in GENERATED_DIRS for part in pure.parts[:-1]):
        return True
    files = parse_unified_diff(diff_text, path=path) if diff_text else []
    return any(_has_marker(f) or _looks_minified(path, f) for f in files)


def _has_marker(file_diff: FileDiff) -> bool:
    for line in _existing_lines(file_diff):
        number = line.old_no
        if number is not None and number <= _MARKER_LINE_LIMIT and _MARKERS.search(line.text):
            return True
    return False


def _looks_minified(path: str, file_diff: FileDiff) -> bool:
    if not path.endswith(_MINIFIED_SUFFIXES):
        return False
    return any(len(line.text) >= _MINIFIED_LINE_CHARS for line in _existing_lines(file_diff))


def _existing_lines(file_diff: FileDiff) -> list[DiffLine]:
    return [line for hunk in file_diff.hunks for line in hunk.lines if line.kind != "+"]
