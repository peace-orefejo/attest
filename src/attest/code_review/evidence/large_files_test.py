import pytest

from attest.code_review.evidence.large_files import (
    EvidenceLimits,
    Omission,
    is_generated,
    render_diff,
    render_diffs,
)

SMALL = "--- a/app.py\n+++ b/app.py\n@@ -1,2 +1,2 @@\n x = 1\n-y = 2\n+y = 3\n"


def _hunks(path: str, count: int, lines_per_hunk: int = 20) -> str:
    parts = [f"--- a/{path}\n+++ b/{path}\n"]
    for index in range(count):
        start = index * 100 + 1
        body = "".join(f"+    value_{index}_{n} = compute({n})\n" for n in range(lines_per_hunk))
        parts.append(f"@@ -{start},0 +{start},{lines_per_hunk} @@\n{body}")
    return "".join(parts)


def _big_npm_lock(packages: int) -> str:
    parts = ["--- a/package-lock.json\n+++ b/package-lock.json\n"]
    for index in range(packages):
        start = index * 10 + 1
        parts.append(
            f"@@ -{start},3 +{start},3 @@\n"
            f'     "node_modules/pkg-{index}": {{\n'
            f'-      "version": "1.0.{index}",\n'
            f'-      "resolved": "https://registry.npmjs.org/pkg-{index}/-/pkg-{index}-1.0.{index}.tgz",\n'
            f'+      "version": "1.1.{index}",\n'
            f'+      "resolved": "https://registry.npmjs.org/pkg-{index}/-/pkg-{index}-1.1.{index}.tgz",\n'
        )
    return "".join(parts)


@pytest.mark.parametrize(
    "path",
    [
        "package-lock.json",
        "web/yarn.lock",
        "Gemfile.lock",
        "composer.lock",
        "static/app.min.js",
        "assets/site.min.css",
        "api/service.pb.go",
        "proto/user_pb2.py",
        "node_modules/left-pad/index.js",
        "vendor/github.com/pkg/errors/errors.go",
        "web/dist/main.js",
        "build/output.css",
        "src/__generated__/graphql.ts",
    ],
)
def test_generated_by_path(path):
    assert is_generated(path)


@pytest.mark.parametrize(
    "path",
    [
        "src/app.py",
        "build.gradle",
        "docs/building.md",
        "migrations/0001_initial.py",
        "src/distance.ts",
    ],
)
def test_hand_written_paths(path):
    assert not is_generated(path, SMALL)


@pytest.mark.parametrize(
    "marker",
    [
        "// Code generated by protoc-gen-go. DO NOT EDIT.",
        "# @generated by tooling",
        "/* This file is auto-generated */",
    ],
)
def test_generated_marker_near_top(marker):
    diff = f"--- a/x.go\n+++ b/x.go\n@@ -1,2 +1,3 @@\n {marker}\n package x\n+var y = 1\n"
    assert is_generated("x.go", diff)


@pytest.mark.parametrize(
    "marker",
    [
        "// Code generated by protoc-gen-go. DO NOT EDIT.",
        "# @generated by tooling",
    ],
)
def test_a_marker_the_pull_request_adds_does_not_hide_the_file(marker):
    diff = f"--- a/x.go\n+++ b/x.go\n@@ -0,0 +1,2 @@\n+{marker}\n+package x\n"
    assert not is_generated("x.go", diff)
    item = render_diff("x.go", diff, EvidenceLimits())
    assert "package x" in item.text
    assert item.omission is None


def test_marker_deep_in_file_is_ignored():
    diff = "--- a/x.py\n+++ b/x.py\n@@ -200,1 +200,2 @@\n x = 1\n+# DO NOT EDIT the next line\n"
    assert not is_generated("x.py", diff)


def test_minified_long_line():
    diff = "--- a/app.js\n+++ b/app.js\n@@ -1 +1 @@\n-" + "a=1;" * 400 + "\n+x\n"
    assert is_generated("app.js", diff)
    assert not is_generated("app.py", diff)


def test_a_long_line_the_pull_request_adds_does_not_hide_the_file():
    diff = "--- a/app.js\n+++ b/app.js\n@@ -1 +1 @@\n-x\n+" + "a=1;" * 400 + "\n"
    assert not is_generated("app.js", diff)


def test_small_hand_written_diff_is_kept_whole():
    item = render_diff("app.py", SMALL, EvidenceLimits())
    assert item.text == SMALL
    assert item.omission is None


def test_known_lockfile_is_summarized():
    diff = "@@ -1,2 +1,2 @@\n-x v1.0.0 h1:abc=\n+x v1.1.0 h1:def=\n"
    item = render_diff("go.sum", diff, EvidenceLimits())
    assert item.text.splitlines()[1].split() == ["x", "v1.0.0", "->", "v1.1.0"]
    assert item.omission == Omission(path="go.sum", reason="summarized", changed_lines=2)


def test_five_thousand_line_lockfile_becomes_short_summary():
    diff = _big_npm_lock(1000)
    assert len(diff.splitlines()) > 5000
    item = render_diff("package-lock.json", diff, EvidenceLimits())
    lines = item.text.splitlines()
    assert lines[0] == "package-lock.json (generated, 4000 lines changed; summarized)"
    assert len(lines) <= 42
    assert lines[-1] == "  ... and 960 more changes"
    assert len(item.text) < 2_000


def test_unparseable_lockfile_becomes_omission_note():
    item = render_diff("yarn.lock", "@@ -1 +1 @@\n-???\n+!!!\n", EvidenceLimits())
    assert item.text == "yarn.lock (generated, 2 lines changed; diff omitted)"
    assert item.omission == Omission(path="yarn.lock", reason="generated", changed_lines=2)


def test_unknown_generated_file_becomes_omission_note():
    diff = "--- a/dist/app.js\n+++ b/dist/app.js\n@@ -1,1 +1,2 @@\n-a\n+b\n+c\n"
    item = render_diff("dist/app.js", diff, EvidenceLimits())
    assert item.text == "dist/app.js (generated, 3 lines changed; diff omitted)"
    assert item.omission.reason == "generated"


def test_large_hand_written_file_keeps_first_hunks():
    diff = _hunks("src/service.py", 10)
    item = render_diff("src/service.py", diff, EvidenceLimits(max_file_chars=2_000))
    assert item.text.startswith("@@ -1,0 +1,20 @@")
    assert "value_0_0" in item.text
    assert "value_9_0" not in item.text
    assert item.omission.reason == "truncated"
    assert item.omission.omitted_hunks > 0
    note = item.text.splitlines()[-1]
    assert f"{item.omission.omitted_hunks} of 10 hunks omitted" in note
    assert "2000 character limit" in note


def test_single_giant_hunk_is_cut_by_lines():
    diff = _hunks("src/new_module.py", 1, lines_per_hunk=2_000)
    item = render_diff("src/new_module.py", diff, EvidenceLimits(max_file_chars=3_000))
    assert len(item.text) < 3_300
    assert "first hunk was cut short" in item.text
    assert item.omission.reason == "truncated"


def test_run_budget_turns_later_diffs_into_notes():
    first = _hunks("a.py", 1, lines_per_hunk=30)
    second = _hunks("b.py", 1, lines_per_hunk=30)
    third = SMALL
    limits = EvidenceLimits(max_file_chars=5_000, max_run_chars=len(first) + 10)
    rendered = render_diffs([("a.py", first), ("b.py", second), ("app.py", third)], limits)
    assert rendered[0].text == first
    assert rendered[0].omission is None
    assert [r.omission.reason for r in rendered[1:]] == ["budget", "budget"]
    assert rendered[1].text.startswith("b.py (30 lines changed; diff omitted")
    assert rendered[2].path == "app.py"


def test_limits_must_be_positive():
    with pytest.raises(ValueError):
        EvidenceLimits(max_file_chars=0)
