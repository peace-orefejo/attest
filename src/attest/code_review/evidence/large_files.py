"""Size limits, generated-file detection, and rendering diffs within those limits."""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import PurePosixPath
from typing import Literal

from ...utils.diff import FileDiff, cut_hunks, parse_unified_diff
from .lockfiles import parser_for, summarize_lockfile

OmissionReason = Literal["summarized", "generated", "truncated", "budget", "out_of_scope"]

GENERATED_FILENAMES = frozenset({
    "Gemfile.lock", "composer.lock", "Pipfile.lock", "bun.lockb", "bun.lock", "flake.lock",
    "Podfile.lock", "mix.lock", "pubspec.lock", "packages.lock.json", "gradle.lockfile",
    "Package.resolved", "deno.lock", "Manifest.toml",
})
GENERATED_SUFFIXES = (
    ".min.js", ".min.mjs", ".min.css", "-min.js", ".bundle.js", ".chunk.js", ".js.map",
    ".css.map", ".pb.go", "_pb2.py", "_pb2_grpc.py", ".pb.cc", ".pb.h", ".g.dart",
    ".freezed.dart", ".designer.cs",
)
GENERATED_DIRS = frozenset({
    "node_modules", "vendor", "third_party", "dist", "build", ".next", ".nuxt",
    "__generated__", "generated", "bower_components",
})
_MARKERS = re.compile(
    r"@generated|DO NOT EDIT|Code generated by|auto-?generated|automatically generated",
    re.IGNORECASE,
)
_MARKER_LINE_LIMIT = 10
_MINIFIED_SUFFIXES = (".js", ".mjs", ".cjs", ".css")
_MINIFIED_LINE_CHARS = 1000


@dataclass(frozen=True)
class EvidenceLimits:
    max_file_chars: int = 12_000
    max_run_chars: int = 60_000

    def __post_init__(self) -> None:
        if self.max_file_chars <= 0 or self.max_run_chars <= 0:
            raise ValueError("evidence limits must be positive")


@dataclass(frozen=True)
class Omission:
    path: str
    reason: OmissionReason
    changed_lines: int = 0
    omitted_hunks: int = 0


@dataclass(frozen=True)
class RenderedDiff:
    path: str
    text: str
    omission: Omission | None = None


def is_generated(path: str, diff_text: str = "") -> bool:
    """Return True for lockfiles, minified bundles, build or vendor output, and marked files."""
    pure = PurePosixPath(path)
    if parser_for(path) is not None or pure.name in GENERATED_FILENAMES:
        return True
    if pure.name.endswith(GENERATED_SUFFIXES):
        return True
    if any(part in GENERATED_DIRS for part in pure.parts[:-1]):
        return True
    files = parse_unified_diff(diff_text, path=path) if diff_text else []
    return any(_has_marker(f) or _looks_minified(path, f) for f in files)


def _has_marker(file_diff: FileDiff) -> bool:
    for hunk in file_diff.hunks:
        for line in hunk.lines:
            number = line.new_no if line.new_no is not None else line.old_no
            if number is not None and number <= _MARKER_LINE_LIMIT and _MARKERS.search(line.text):
                return True
    return False


def _looks_minified(path: str, file_diff: FileDiff) -> bool:
    if not path.endswith(_MINIFIED_SUFFIXES):
        return False
    return any(len(text) >= _MINIFIED_LINE_CHARS for _, text in file_diff.added_lines())


def changed_lines(path: str, diff_text: str) -> int:
    """Count the added and removed lines in one file's diff."""
    return sum(f.changed_line_count() for f in parse_unified_diff(diff_text, path=path))


def render_diff(path: str, diff_text: str, limits: EvidenceLimits) -> RenderedDiff:
    """Render one file's diff as evidence, summarizing, omitting or cutting it as needed."""
    count = changed_lines(path, diff_text)
    if parser_for(path) is not None:
        summary = summarize_lockfile(path, diff_text)
        if summary is not None:
            return RenderedDiff(path, summary, Omission(path, "summarized", count))
    if is_generated(path, diff_text):
        return RenderedDiff(
            path,
            f"{path} (generated, {count} lines changed; diff omitted)",
            Omission(path, "generated", count),
        )
    if len(diff_text) <= limits.max_file_chars:
        return RenderedDiff(path, diff_text)
    return _truncate(path, diff_text, count, limits.max_file_chars)


def _truncate(path: str, diff_text: str, count: int, max_chars: int) -> RenderedDiff:
    hunks = [h for f in parse_unified_diff(diff_text, path=path) for h in f.hunks]
    if not hunks:
        kept, _ = _cut_lines(diff_text, max_chars)
        note = f"[{path}: diff cut at {max_chars} characters; the rest was omitted]"
        return RenderedDiff(path, f"{kept}\n{note}", Omission(path, "truncated", count))
    kept, omitted = cut_hunks(FileDiff(path=path, hunks=hunks), max_chars)
    notes: list[str] = []
    if len(kept) > max_chars:
        kept, dropped = _cut_lines(kept, max_chars)
        notes.append(f"the first hunk was cut short, dropping {dropped} lines")
    if omitted:
        notes.append(f"{omitted} of {len(hunks)} hunks omitted")
    note = f"[{path}: {'; '.join(notes)}; the file diff exceeds the {max_chars} character limit]"
    return RenderedDiff(path, f"{kept}\n{note}", Omission(path, "truncated", count, omitted))


def _cut_lines(text: str, max_chars: int) -> tuple[str, int]:
    lines = text.splitlines()
    kept: list[str] = []
    used = 0
    for line in lines:
        if kept and used + len(line) + 1 > max_chars:
            break
        kept.append(line[:max_chars])
        used += len(line) + 1
    return "\n".join(kept), len(lines) - len(kept)


def budget_note(path: str, count: int, limits: EvidenceLimits) -> RenderedDiff:
    """Render the omission note for a diff left out because the run budget is used up."""
    text = (f"{path} ({count} lines changed; diff omitted, the run evidence budget of "
            f"{limits.max_run_chars} characters is used up)")
    return RenderedDiff(path, text, Omission(path, "budget", count))


def render_diffs(
    diffs: list[tuple[str, str]], limits: EvidenceLimits | None = None
) -> list[RenderedDiff]:
    """Render diffs in order, turning every diff after the run budget runs out into a note."""
    limits = limits or EvidenceLimits()
    rendered: list[RenderedDiff] = []
    used = 0
    exhausted = False
    for path, diff_text in diffs:
        item = None if exhausted else render_diff(path, diff_text, limits)
        if item is not None and used + len(item.text) > limits.max_run_chars:
            exhausted = True
            item = None
        if item is None:
            item = budget_note(path, changed_lines(path, diff_text), limits)
        else:
            used += len(item.text)
        rendered.append(item)
    return rendered
